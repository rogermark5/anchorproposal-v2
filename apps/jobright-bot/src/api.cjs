class BotApi {
  constructor(base, key, fetcher = fetch) {
    const url = new URL(base);
    if (url.username || url.password || url.search || url.hash || (url.protocol !== 'https:' && !(url.protocol === 'http:' && ['localhost', '127.0.0.1'].includes(url.hostname)))) throw Error('Use HTTPS or a localhost API URL.');
    if (!/^jrbot_[a-f0-9]{64}$/.test(key || '')) throw Error('Set JOBRIGHT_WORKER_KEY using the key generated by Master.');
    this.base = url.toString().replace(/\/$/, '') + '/job-pool/jobright-bot/worker'; this.key = key; this.fetcher = fetcher;
  }
  async call(route, body) {
    if (!(route.startsWith('?instanceId=') || ['/heartbeat', '/jobs'].includes(route))) throw Error('Unsupported worker route');
    for (let attempt = 0; ; attempt++) {
      try {
        const response = await this.fetcher(this.base + route, { method: body ? 'POST' : 'GET',
          headers: { Authorization: 'Bearer ' + this.key, ...(body ? { 'Content-Type': 'application/json' } : {}) },
          ...(body ? { body: JSON.stringify(body) } : {}), signal: AbortSignal.timeout(35000) });
        if ([502, 503, 504].includes(response.status) && attempt < 2) { await response.body?.cancel(); await new Promise(resolve => setTimeout(resolve, 1000 * (attempt + 1))); continue; }
        if (!response.ok) { await response.body?.cancel(); const error = new Error(response.status === 401 ? 'Worker key rejected. Configure the current key and restart this worker.' : 'Bot API returned HTTP ' + response.status); error.status = response.status; throw error; }
        return await response.json();
      } catch (error) { if (error.status || attempt >= 2) throw error; await new Promise(resolve => setTimeout(resolve, 1000 * (attempt + 1))); }
    }
  }
}
module.exports = { BotApi };
