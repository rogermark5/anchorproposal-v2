class BotApiError extends Error {
  constructor(message, status, cause) { super(message, { cause }); this.name = 'BotApiError'; this.safeMessage = message; if (status) this.status = status; }
}
class BotApi {
  constructor(base, key, fetcher = fetch, { pause = ms => new Promise(resolve => setTimeout(resolve, ms)), timeoutMs = 20000 } = {}) {
    const url = new URL(base);
    if (url.username || url.password || url.search || url.hash || (url.protocol !== 'https:' && !(url.protocol === 'http:' && ['localhost', '127.0.0.1'].includes(url.hostname)))) throw Error('Use HTTPS or a localhost API URL.');
    if (!/^jrbot_[a-f0-9]{64}$/.test(key || '')) throw Error('Set JOBRIGHT_WORKER_KEY using the key generated by Master.');
    this.base = url.toString().replace(/\/$/, '') + '/job-pool/jobright-bot/worker'; this.origin = url.origin; this.key = key; this.fetcher = fetcher; this.pause = pause; this.timeoutMs = timeoutMs;
  }
  async call(route, body) {
    if (!(route.startsWith('?instanceId=') || ['/heartbeat', '/jobs'].includes(route))) throw Error('Unsupported worker route');
    for (let attempt = 0; ; attempt++) {
      try {
        const response = await this.fetcher(this.base + route, { method: body ? 'POST' : 'GET',
          headers: { Authorization: 'Bearer ' + this.key, ...(body ? { 'Content-Type': 'application/json' } : {}) },
          ...(body ? { body: JSON.stringify(body) } : {}), signal: AbortSignal.timeout(this.timeoutMs) });
        if ([429, 502, 503, 504].includes(response.status) && attempt < 2) { await response.body?.cancel(); await this.pause(1000 * (attempt + 1)); continue; }
        if (!response.ok) {
          await response.body?.cancel();
          throw new BotApiError(response.status === 401 ? 'Worker key rejected. Configure the current key and restart this worker.' :
            response.status === 409 ? 'The bot is paused, its watch changed, or another worker holds the connection. Refresh the bot status.' :
            'AnchorProposal API returned HTTP ' + response.status + ' at ' + this.origin + '. Check anchor-api and JOBRIGHT_API_URL.', response.status);
        }
        let data;
        try { data = await response.json(); if (!data || typeof data !== 'object' || Array.isArray(data)) throw Error(); }
        catch { throw new BotApiError('AnchorProposal API returned an invalid response. Check JOBRIGHT_API_URL and the /backend proxy if you use the public domain.'); }
        return data;
      } catch (error) {
        if (error instanceof BotApiError) throw error;
        if (attempt >= 2) {
          const code = error.cause?.code || error.code || error.name;
          const reason = /^(?:ECONNREFUSED|ECONNRESET|ENOTFOUND|EAI_AGAIN|ETIMEDOUT|UND_ERR_[A-Z_]+|CERT_[A-Z_]+|TimeoutError|AbortError)$/.test(code) ? code : 'network connection failed';
          throw new BotApiError('Could not reach AnchorProposal API at ' + this.origin + ' (' + reason + '). Check anchor-api, network access and JOBRIGHT_API_URL. The saved checkpoint was kept.', undefined, error);
        }
        await this.pause(1000 * (attempt + 1));
      }
    }
  }
}
module.exports = { BotApi, BotApiError };
